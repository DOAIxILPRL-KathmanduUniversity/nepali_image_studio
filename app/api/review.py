"""API routes for reviewing and approving AI-submitted annotations."""
from typing import List, Optional
from fastapi import APIRouter, Depends, HTTPException, Query, status
from sqlalchemy import select, func, update
from sqlalchemy.ext.asyncio import AsyncSession
from ..database import get_db
from ..models import Image as ImageModel
from ..schemas import ImageOut, ReviewAction

router = APIRouter(prefix="/api/review", tags=["review"])


@router.get("/pending", response_model=List[ImageOut])
async def list_pending_ai_annotations(
    page: int = Query(1, ge=1),
    limit: int = Query(25, ge=1, le=100),
    db: AsyncSession = Depends(get_db),
):
    """
    List annotations generated by AI agents (via MCP) awaiting human review and approval.
    """
    stmt = select(ImageModel).where(
        ImageModel.annotation_source == "ai_pending",
        ImageModel.is_approved == False,
    ).order_by(ImageModel.updated_at.desc()).offset((page - 1) * limit).limit(limit)

    res = await db.execute(stmt)
    return res.scalars().all()


@router.post("/{image_id}/action", response_model=ImageOut)
async def review_ai_annotation(
    image_id: int,
    action_data: ReviewAction,
    db: AsyncSession = Depends(get_db),
):
    """
    Human action on an AI annotation:
    - 'approve': Approves the AI annotation directly (annotation_source becomes 'ai_approved')
    - 'reject': Clears the AI fields, resets status to 'ready'
    - 'edit': Applies human corrections, sets annotation_source='manual' (auto-approved)
    """
    stmt = select(ImageModel).where(ImageModel.id == image_id)
    res = await db.execute(stmt)
    img = res.scalars().first()
    if not img:
        raise HTTPException(status_code=404, detail="Image not found")

    if action_data.action == "approve":
        img.is_approved = True
        img.annotation_source = "ai_approved"
        img.status = "approved"

    elif action_data.action == "reject":
        # Clear AI generated drafts
        img.annotation_text = None
        img.ocr_text = None
        img.caption_nepali = None
        img.caption_english = None
        img.ai_output = None
        img.has_text = False
        img.annotation_source = None
        img.is_approved = False
        img.status = "ready"

    elif action_data.action == "edit":
        if action_data.edited_text is not None:
            img.annotation_text = action_data.edited_text
            img.ocr_text = action_data.edited_text
            img.has_text = bool(action_data.edited_text.strip())
        if action_data.edited_caption_nepali is not None:
            img.caption_nepali = action_data.edited_caption_nepali
        if action_data.edited_caption_english is not None:
            img.caption_english = action_data.edited_caption_english

        img.annotation_source = "manual"
        img.annotated_by = "user"
        img.is_approved = True
        img.status = "approved"

    await db.commit()
    await db.refresh(img)
    return img


@router.post("/bulk-approve")
async def bulk_approve_pending(
    image_ids: List[int],
    db: AsyncSession = Depends(get_db),
):
    """Approve a batch of verified AI annotations in one click."""
    stmt = update(ImageModel).where(
        ImageModel.id.in_(image_ids),
        ImageModel.annotation_source == "ai_pending",
    ).values(
        is_approved=True,
        annotation_source="ai_approved",
        status="approved",
    )
    res = await db.execute(stmt)
    await db.commit()
    return {"approved_count": res.rowcount}
